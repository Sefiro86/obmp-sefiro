-- The variant's skin on the body materials: each slot becomes (if it is not already) a dynamic instance and receives
-- the variant's albedo and NNRS. Redone in maintain (every 0.5 s) because the race's senescence may overwrite them.
-- Only when the main mesh is already the Succubus body (right after the race change the old one is still there).
local midClass = nil
local NAME_BASE, NAME_NNR = nil, nil
local function applySkin(st)
    local sk = st.def.skinTex
    if not sk then return end
    local meshName = ""
    pcall(function() meshName = fullName(st.m.SkeletalMesh) end)
    if meshName == "" or meshName == st.humanMesh then return end   -- the human body is still there: the race comes later
    local alb, nnr = StaticFindObject(sk.albedo), StaticFindObject(sk.nnr)
    if not valid(alb) or not valid(nnr) then
        if not st.skinMissingLogged then
            st.skinMissingLogged = true
            log("skin of " .. st.creature .. ": textures not in memory (" .. (valid(alb) and sk.nnr or sk.albedo) .. ")")
        end
        return
    end
    if not valid(midClass) then midClass = StaticFindObject("/Script/Engine.MaterialInstanceDynamic") end
    if not NAME_BASE then NAME_BASE, NAME_NNR = FName("BaseColor Map"), FName("NNR Map") end
    local n, changed = st.m:GetNumMaterials(), 0
    for i = 0, n - 1 do
        local mat = st.m:GetMaterial(i)
        if valid(mat) then
            local mid = mat
            if not mat:IsA(midClass) then mid = st.m:CreateDynamicMaterialInstance(i, mat, FName("None")) end
            if valid(mid) then
                local cur = nil
                pcall(function() cur = mid:K2_GetTextureParameterValue(NAME_BASE) end)
                if addrOf(cur) ~= addrOf(alb) then
                    mid:SetTextureParameterValue(NAME_BASE, alb)
                    mid:SetTextureParameterValue(NAME_NNR, nnr)
                    changed = changed + 1
                end
            end
        end
    end
    if changed > 0 then
        st.skinSets = (st.skinSets or 0) + 1
        if st.skinSets <= 3 or st.skinSets % 50 == 0 then
            log(string.format("skin of %s on %d/%d materials of %s (application no. %d)", st.creature, changed, n,
                meshName:match("[^%.]+$") or meshName, st.skinSets))
        end
    end
end

-- ---------------------------------------------------------------- creature sounds (2026-11-17)
-- The creature's Wwise events (WwiseAudio/creature/<X>/cre_<x>_attack|aware|death|footstep|idle|pain, from the data
-- file). Footsteps are already notifies in the creature's animations. The game plays pawn.PainEvent and
-- pawn.FootstepEvent (VPairedPawn) by itself: during the form the creature's ones are set and on return the previous ones.
-- Attack with the montage, alert when the weapon is drawn, idle sound every 15-40 s when standing still.
-- No LoadAsset: only the events that the game already has in memory are used (creature preload).
local akStatics = nil
local function soundEvent(st, kind)
    local path = st.def.sounds and st.def.sounds[kind]
    if not path then return nil end
    local ev = ensure(path, "AkAudioEvent")
    if ev and not loadedFully(ev) then return nil end
    return ev
end
-- PostEventAtLocation only (event, position, rotation, context): simple parameters. The component's PostAkEvent
-- has a callback delegate as a parameter and passing it {} from Lua made UE4SS crash (2026-11-17 03:11:54, AV in
-- UE4SS.dll on the stag's first attack). The event stays at the pawn's spot: the sounds are short.
local function playSound(st, kind)
    local ev = soundEvent(st, kind)
    if not ev then return false end
    local ok, err = pcall(function()
        if not valid(akStatics) then akStatics = StaticFindObject("/Script/AkAudio.Default__AkGameplayStatics") end
        akStatics:PostEventAtLocation(ev, st.pawn:K2_GetActorLocation(), { Pitch = 0, Yaw = 0, Roll = 0 }, st.pawn)
    end)
    if not ok and not st.soundErrLogged then st.soundErrLogged = true; log("sounds: unable to play " .. kind .. ": " .. tostring(err):sub(1, 120)) end
    return ok
end
local SOUND_PROPS = { pain = "PainEvent", footstep = "FootstepEvent" }
local function swapSounds(st)
    st.soundsWas = {}
    local have = 0
    for kind, prop in pairs(SOUND_PROPS) do
        local ev = soundEvent(st, kind)
        if ev then
            pcall(function() st.soundsWas[prop] = st.pawn[prop]; st.pawn[prop] = ev end)
        elseif st.def.sounds and st.def.sounds[kind] then
            st.soundRetry = true   -- the event arrives with the preload: soundTick retries for 10 s
        end
    end
    local list = {}
    for _, kind in ipairs({ "attack", "aware", "death", "footstep", "idle", "pain" }) do
        if st.def.sounds and st.def.sounds[kind] then
            if soundEvent(st, kind) then have = have + 1; list[#list + 1] = kind else list[#list + 1] = kind .. "(not in memory)" end
        end
    end
    log(string.format("sounds of %s: %d in memory [%s]", st.creature, have, table.concat(list, ", ")))
end
local function restoreSounds(st)
    if not st.soundsWas or not valid(st.pawn) then return end
    for prop, ev in pairs(st.soundsWas) do
        pcall(function() st.pawn[prop] = ev end)
    end
end
local function soundTick(st)
    if st.soundRetry then   -- pain/footstep events not yet in memory at apply time
        st.soundRetryUntil = st.soundRetryUntil or (tickCount + 100)
        st.soundRetry = false
        for kind, prop in pairs(SOUND_PROPS) do
            if st.soundsWas[prop] == nil and st.def.sounds and st.def.sounds[kind] then
                local ev = soundEvent(st, kind)
                if ev then pcall(function() st.soundsWas[prop] = st.pawn[prop]; st.pawn[prop] = ev end)
                elseif tickCount < st.soundRetryUntil then st.soundRetry = true end
            end
        end
    end
    -- alert: weapon drawn (entering combat), at most once every 20 s
    local drawn = false
    pcall(function() drawn = st.pawn:IsWeaponDrawn() end)
    if drawn and not st.wasDrawn and tickCount >= (st.nextAware or 0) then
        playSound(st, "aware")
        st.nextAware = tickCount + 200
    end
    st.wasDrawn = drawn
    -- idle sound: standing still and no recent attacks
    if not st.nextIdle then st.nextIdle = tickCount + math.random(150, 400) end
    if tickCount >= st.nextIdle then
        local speed = 0
        pcall(function() local v = st.pawn.CharacterMovement.Velocity; speed = v.X * v.X + v.Y * v.Y end)
        if speed < 2500 and tickCount - (st.lastAttackTick or -1000) > 100 then playSound(st, "idle") end
        st.nextIdle = tickCount + math.random(150, 400)
    end
end

local function applyRace(key, pawn, name, def)
    local race = StaticFindObject(def.race)
    if not valid(race) then return "loading", def.race end
    if not loadedFully(race) then return "loading", def.race .. " (loading in progress)" end
    local m = nil
    pcall(function() m = pawn.MainSkeletalMeshComponent end)
    if not valid(m) then log("the pawn has no MainSkeletalMeshComponent: " .. fullName(pawn)); return "fail" end
    local st = { creature = name, def = def, kind = "race", mode = "R", pawn = pawn, pawnAddr = addrOf(pawn), m = m,
                 parts = {}, hiddenComps = {}, hiddenActors = {}, mats = {}, raceObj = race }
    st.raceWas = raceOf(pawn)
    pcall(function() st.humanMesh = fullName(m.SkeletalMesh) end)
    local ok, err = setRace(pawn, race)
    if not ok then log("race change failed: " .. tostring(err):sub(1, 160)); return "fail" end
    hideHuman(st)
    active[key] = st
    local okSkin, errSkin = pcall(applySkin, st)
    if not okSkin then log("skin: " .. tostring(errSkin)) end
    local mesh, merged = "?", "?"
    pcall(function() mesh = fullName(m.SkeletalMesh) end)
    pcall(function() merged = tostring(pawn.MergedMeshComponent.MergedMeshComponent.bHiddenInGame) end)
    log(string.format("transformed %s (%s) into %s: race %s -> %s, body %s, merged mesh hidden=%s, %d hidden components",
        key, fullName(pawn), name, fullName(st.raceWas), fullName(race), mesh, merged, countOf(st.hiddenComps)))
    return "ok"
end

local function apply(key, pawn, name)
    local def = CREATURES[name]
    if not def then log("unknown creature: " .. tostring(name)); return "fail" end
    if def.kind == "race" then return applyRace(key, pawn, name, def) end

    -- 1. assets loaded?
    local objs, missing = {}, nil
    for _, a in ipairs(assetsOf(def)) do
        local p = a[1]
        objs[p] = ensure(p, a[2])
        if not objs[p] then
            missing = missing or p
        elseif not loadedFully(objs[p]) then
            missing = missing or (p .. " (loading in progress)")
        end
    end
    if missing then return "loading", missing end
    -- all ready: we still wait READY_TICKS before touching the body
    local wait = readyWait[key]
    if not wait or wait.creature ~= name then
        wait = { creature = name, at = tickCount + READY_TICKS }
        readyWait[key] = wait
        log("assets of " .. name .. " in memory, applying in 1.5 s")
    end
    if tickCount < wait.at then return "loading", "waiting for dependencies" end
    readyWait[key] = nil

    local m, sm = nil, nil
    pcall(function() m = pawn.MainSkeletalMeshComponent end)
    pcall(function() sm = pawn.StateMachineComponent end)
    if not valid(m) then log("the pawn has no MainSkeletalMeshComponent: " .. fullName(pawn)); return "fail" end

    local mode = MODES[MODE_INDEX]
    local st = { creature = name, def = def, pawn = pawn, pawnAddr = addrOf(pawn), m = m, sm = sm, mode = mode,
                 parts = {}, hiddenComps = {}, hiddenActors = {}, mats = {} }
    pcall(function() st.mesh = m.SkeletalMesh end)
    pcall(function() st.anim = m.AnimClass end)
    pcall(function() if valid(sm) then st.presets = sm.ActionStatePresetsDataTable end end)
    pcall(function() st.tickWas = m.VisibilityBasedAnimTickOption end)
    pcall(function() st.mainHiddenWas = m.bHiddenInGame == true end)

    local skc = StaticFindObject("/Script/Engine.SkeletalMeshComponent")

    -- 2. holder: keeps the original mesh and materials alive for as long as the form lasts (A only: in B/C the mesh stays)
    if mode == "A" then pcall(function()
        local n = m:GetNumMaterials()
        for i = 0, n - 1 do st.mats[i] = m:GetMaterial(i) end
        local holder = pawn:AddComponentByClass(skc, true, NO_MOVE, false)
        pcall(function() holder:SetHiddenInGame(true, false) end)
        pcall(function() holder:SetCollisionEnabled(0) end)
        if valid(st.mesh) then setMesh(holder, st.mesh) end
        for i = 0, n - 1 do if valid(st.mats[i]) then holder:SetMaterial(i, st.mats[i]) end end
        st.holder = holder
    end) end
    if mode == "A" and not valid(st.holder) then log("holder not created: the form does not start (GC risk on return)"); return "fail" end

    -- 3. human parts and attached actors hidden, body hidden until the animation starts
    hideHuman(st)
    pcall(function() m:SetHiddenInGame(true, false) end)
    st.revealTick = tickCount + REVEAL_TICKS

    -- 4. the creature's body, animations and actions
    pcall(function() m.VisibilityBasedAnimTickOption = 0 end)   -- AlwaysTickPoseAndRefreshBones (even when hidden)
    if mode == "A" then
        st.body = m
    else
        pcall(function()
            local b = pawn:AddComponentByClass(skc, true, NO_MOVE, false)
            b:K2_AttachToComponent(m, FName("None"), 2, 2, 2, false)
            pcall(function() b:SetCollisionEnabled(0) end)
            pcall(function() b.bUseAttachParentBound = true end)
            pcall(function() b.VisibilityBasedAnimTickOption = 0 end)
            pcall(function() b:SetHiddenInGame(true, false) end)
            st.body = b
        end)
        if not valid(st.body) then log("body component not created"); return "fail" end
    end
    wearBody(st, objs[def.body], objs[def.abp])
    local swap = SWAP_PRESETS and mode ~= "C"
    if valid(sm) and swap then pcall(function() sm.ActionStatePresetsDataTable = objs[def.presets] end) end
    st.swapped = swap

    -- 5. fur, horns, bags: components in leader pose on the body
    for _, p in ipairs(def.parts) do
        pcall(function()
            local c = pawn:AddComponentByClass(skc, true, NO_MOVE, false)
            c:K2_AttachToComponent(st.body, FName("None"), 2, 2, 2, false)
            setMesh(c, objs[p])
            pcall(function()
                objs[p].Materials:ForEach(function(i, e)
                    local mat = e:get().MaterialInterface
                    if valid(mat) then c:SetMaterial(i - 1, mat) end
                end)
            end)
            if not pcall(function() c:SetLeaderPoseComponent(st.body, true, false) end) then
                pcall(function() c:SetMasterPoseComponent(st.body, true) end)
            end
            pcall(function() c.bUseAttachParentBound = true end)
            pcall(function() c:SetCollisionEnabled(0) end)
            pcall(function() c:SetHiddenInGame(true, false) end)
            table.insert(st.parts, c)
        end)
    end

    -- 6. human special idles turned off (stretching, looking around...): the creature does not have them and went into A-pose
    pcall(function()
        local apc = pawn.AnimationPairingComponent
        st.specialIdlesWas = apc.bCanPerformSpecialIdles
        apc.bCanPerformSpecialIdles = false
    end)

    -- 7. bare-handed attack reach adapted to the creature (AVPairedPawn.UnarmedAttackReach, this pawn only)
    if REACH[name] then
        pcall(function() st.reachWas = pawn.UnarmedAttackReach; pawn.UnarmedAttackReach = REACH[name] end)
    end

    -- 8. no jumping (creatures do not have the animation)
    if not ALLOW_JUMP then pcall(function() st.jumps = pawn.JumpMaxCount; pawn.JumpMaxCount = 0 end) end

    active[key] = st
    pcall(swapSounds, st)
    if key == "self" then setParallelAnim(false, "the player is " .. name); lastHand = nil end   -- hand.txt rewritten right away
    log(string.format("transformed %s (%s) into %s [mode %s]: %d parts added, %d components and %d actors hidden",
        key, fullName(pawn), name, mode, #st.parts, countOf(st.hiddenComps), countOf(st.hiddenActors)))
    return "ok"
end

local function revert(key)
    local st = active[key]
    if not st then return end
    active[key] = nil
    if st.kind == "race" then
        if valid(st.pawn) and st.raceWas ~= nil then
            local ok, err = setRace(st.pawn, st.raceWas)
            if not ok then log("race restore failed: " .. tostring(err):sub(1, 160)) end
        end
        showHuman(st)
        log("transformation " .. st.creature .. " removed from " .. key)
        unpreload(st.creature)
        return
    end
    for _, c in ipairs(st.parts) do
        if valid(c) then pcall(function() c:K2_DestroyComponent(c) end) end
    end
    if st.mode ~= "A" and valid(st.body) then pcall(function() st.body:K2_DestroyComponent(st.body) end) end
    if valid(st.pawn) and valid(st.m) then
        local m = st.m
        if valid(st.sm) and st.swapped and st.presets ~= nil then pcall(function() st.sm.ActionStatePresetsDataTable = st.presets end) end
        pcall(function() m:SetHiddenInGame(true, false) end)
        if st.mode == "A" then
            if valid(st.mesh) then setMesh(m, st.mesh) end
            for i, mat in pairs(st.mats) do
                if valid(mat) then pcall(function() m:SetMaterial(i, mat) end) end
            end
            if st.anim ~= nil then pcall(function() m:SetAnimClass(st.anim) end) end
        end
        if st.tickWas ~= nil then pcall(function() m.VisibilityBasedAnimTickOption = st.tickWas end) end
        if st.jumps ~= nil then pcall(function() st.pawn.JumpMaxCount = st.jumps end) end
        if st.reachWas ~= nil then pcall(function() st.pawn.UnarmedAttackReach = st.reachWas end) end
        pcall(restoreSounds, st)
        if st.specialIdlesWas ~= nil then
            pcall(function() st.pawn.AnimationPairingComponent.bCanPerformSpecialIdles = st.specialIdlesWas end)
        end
        showHuman(st)
        table.insert(showLater, { comp = m, hidden = st.mainHiddenWas == true, at = tickCount + 4 })
    end
    -- the holder is removed last: now the mesh and materials are referenced by the body again
    if valid(st.holder) then pcall(function() st.holder:K2_DestroyComponent(st.holder) end) end
    if key == "self" then setParallelAnim(true, "form removed") end
    log("transformation " .. st.creature .. " removed from " .. key)
    unpreload(st.creature)
end

-- Every 0.5 s: new equipment to hide; if the game put the human body back, it is swapped again.
local function maintain(st)
    if st.kind ~= "race" and valid(st.body) then pcall(forceGameThreadAnim, st) end   -- instance recreated by the game?
    hideHuman(st)
    if st.kind == "race" then
        -- the game may reapply the original race (loading, synchronization): ours is put back
        if valid(st.raceObj) and addrOf(raceOf(st.pawn)) ~= addrOf(st.raceObj) then
            log("the game put the race of " .. fullName(st.pawn) .. " back: changing it again")
            setRace(st.pawn, st.raceObj)
        end
        local okSkin, errSkin = pcall(applySkin, st)
        if not okSkin and not st.skinErrLogged then st.skinErrLogged = true; log("skin: " .. tostring(errSkin)) end
        return
    end
    if st.mode ~= "A" then
        -- B/C: the human mesh must stay hidden (the game may show it again)
        pcall(function() if not st.m.bHiddenInGame then st.m:SetHiddenInGame(true, false) end end)
        return
    end
    local body = StaticFindObject(canonical[st.def.body] or st.def.body)
