local PACKS = {}          -- id -> pack read (including unavailable ones, for the log)
local loadedFiles = {}    -- packs\ files already read
local KEEP_VISIBLE = { "obmp" }
local function loadPacks()
    local names = {}
    -- file list: packs\list.txt if present (one line per file), otherwise "dir" (once, at startup)
    local list = readFile(MOD_DIR .. "\\packs\\list.txt")
    if list then
        for line in list:gmatch("[^\r\n]+") do if line:find("%.json$") then names[#names + 1] = line end end
    else
        local okP, p = pcall(io.popen, 'dir /b "' .. MOD_DIR .. '\\packs\\*.json" 2>nul')
        if okP and p then for line in p:lines() do names[#names + 1] = line end; p:close() end
    end
    for _, file in ipairs(names) do
        if loadedFiles[file] then goto continue end   -- already read (even if discarded): rereading skips it
        loadedFiles[file] = true
        local okJ, pack = pcall(jsonDecode, readFile(MOD_DIR .. "\\packs\\" .. file) or "")
        local why = nil
        if not okJ or type(pack) ~= "table" or type(pack.id) ~= "string" or not pack.race then
            why = "invalid file: " .. tostring(okJ and "missing fields" or pack)
        elseif pack.requires and pack.requires.pak and not readFile(GAME_CONTENT .. "\\Paks\\~mods\\" .. pack.requires.pak) then
            why = "pak " .. pack.requires.pak .. " not installed"
        elseif pack.requires and pack.requires.plugin and not PLUGIN_INDEX[pack.requires.plugin:lower()] then
            why = "plugin " .. pack.requires.plugin .. " not in Plugins.txt"
        end
        if why then
            print(TAG .. "pack " .. file .. " not available: " .. why .. "\n")
        else
            local forms = {}
            for _, f in ipairs(pack.preload or {}) do
                local idx = PLUGIN_INDEX[(f.plugin or ""):lower()]
                local local_id = tonumber(f.id or "", 16)
                if idx and local_id then forms[#forms + 1] = idx * 0x1000000 + (local_id & 0xFFFFFF) end
            end
            for _, k in ipairs(pack.keepVisible or {}) do KEEP_VISIBLE[#KEEP_VISIBLE + 1] = k:lower() end
            local skins = pack.skins or {}
            if #skins == 0 then skins = { { id = "default" } } end
            for i, skin in ipairs(skins) do
                local key = "pack:" .. pack.id .. (i == 1 and "" or (":" .. skin.id))
                CREATURES[key] = { kind = "race", race = pack.race, forms = forms, pack = pack.id,
                                   skinTex = (skin.albedo and skin.nnr) and { albedo = skin.albedo, nnr = skin.nnr } or nil }
                table.insert(CYCLE, key)
            end
            PACKS[pack.id] = pack
            print(TAG .. "pack " .. pack.id .. ": " .. #skins .. " skins, preloaded forms " .. #forms .. "\n")
        end
        ::continue::
    end
end
