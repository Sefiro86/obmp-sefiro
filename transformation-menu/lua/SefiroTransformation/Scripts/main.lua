        pcall(function() st.body:K2_AttachToComponent(st.m, FName("None"), 2, 2, 2, false) end)
        log("the creature gets back up")
    end
end

-- Frozen pose (2026-11-17, stag: after a few seconds of running the body stays still and slides). Every tick the
-- position of a bone far from the root is compared, in component space: if it stays identical for 1 s
-- the animation is no longer updating. The state of the component and of the AnimInstance is written and we try to restart,
-- one step at a time (tick re-enabled, pause removed, AnimBlueprint put back), noting in the log which step works.
local function freezeTick(st)
    local b = st.body
    if st.probeOff or not valid(b) or st.revealTick then return end
    if not st.probeBones then
        local n = 0
        local okN, errN = pcall(function() n = b:GetNumBones() end)
        if n < 4 then
            if not st.probeErr then st.probeErr = true; log("pose check: bones " .. tostring(n) .. " " .. tostring(errN)) end
            return
        end
        -- three bones spread across the hierarchy (legs, tail, neck): a single one might be a never-animated bone
        st.probeBones = { b:GetBoneName(n // 4), b:GetBoneName(n // 2), b:GetBoneName(n - 2) }
        st.probeBone = st.probeBones[2]
    end
    local speed = 0   -- when standing still a nearly motionless idle must not look like a stuck pose: we only count while moving
    pcall(function() local v = st.pawn.CharacterMovement.Velocity; speed = v.X * v.X + v.Y * v.Y end)
    local frozen = st.frozenTicks or 0
    if speed < 2500 and frozen < 2 then st.frozenTicks = 0; st.probeSum = nil; return end   -- below 50 cm/s
    -- sum of the three bones' coordinates in component space (turning does not change it): a single number,
    -- no strings or tables at every check
    local sum = 0
    for i = 1, 3 do
        -- GetBoneLocation(nome, EBoneSpaces::ComponentSpace = 1)
        local okL, loc = pcall(function() return b:GetBoneLocation(st.probeBones[i], 1) end)
        if not okL or not loc then
            -- trial 2026-11-17 02:55: "UObject instance is nullptr" on GetBoneLocation of the added body. The check
            -- is turned off for this form instead of retrying every 0.5 s (the two known causes, block and drawn weapon, already
            -- have their own fix)
            if not st.probeErr then st.probeErr = true; log("pose check turned off for this form: " .. tostring(loc):sub(1, 120)) end
            st.probeOff = true
            return
        end
        sum = sum + loc.X * 1.0 + loc.Y * 3.1 + loc.Z * 7.3
    end
    if DEBUG then log(string.format("pose check %s: sum %.3f, speed %.0f, frozen %d", st.creature, sum, math.sqrt(speed), frozen)) end
    if st.probeSum and math.abs(sum - st.probeSum) < 0.001 then frozen = frozen + 1 else
        if frozen >= 2 then log(string.format("pose moving again after %.1f s (step %d)", frozen / 2, st.unfreezeStep or 0)) end
        frozen, st.unfreezeStep = 0, 0
    end
    st.frozenTicks, st.probeSum = frozen, sum
    if frozen == 2 or (frozen > 2 and frozen % 4 == 0) then   -- frozen for 1 s, then every 2 s
        local inst, tickOn, paused, vis, noSkel, cls = nil, "?", "?", "?", "?", "?"
        pcall(function() inst = b:GetAnimInstance() end)
        pcall(function() tickOn = tostring(b:IsComponentTickEnabled()) end)
        pcall(function() paused = tostring(b.bPauseAnims) end)
        pcall(function() vis = tostring(b:IsVisible()) end)
        pcall(function() noSkel = tostring(b.bNoSkeletonUpdate) end)
        pcall(function() cls = fullName(inst:GetClass()):match("[^%.]+$") end)
        log(string.format("FROZEN POSE for %.1f s (%s, bone %s): tick=%s pause=%s visible=%s noSkeletonUpdate=%s anim=%s (%s)",
            st.frozenTicks / 2, st.creature, tostring(st.probeBone and st.probeBone:ToString()), tickOn, paused, vis,
            noSkel, valid(inst) and "valid" or "NOT valid", cls))
        st.unfreezeStep = (st.unfreezeStep or 0) + 1
        if st.unfreezeStep == 1 then
            pcall(function() b:SetComponentTickEnabled(true) end)
            pcall(function() b.bNoSkeletonUpdate = false end)
            pcall(function() b.bPauseAnims = false end)
            pcall(function() b.VisibilityBasedAnimTickOption = 0 end)
            log("step 1: tick, skeleton update and animations re-enabled")
        end   -- no SetAnimClass during the game: it blocked ReadyM's main.dll (see blockTick)
    end
end

-- Weapon drawn on creatures without combat locomotion (bear, sheep, ghost, lich: no
-- HandToHand/Locomotion). With the weapon drawn their AnimBlueprint has no animations and the body stays still (bear,
-- 2026-11-17, arrived with a raised fist from the stag). If the weapon stays drawn for 1.5 s without attacks, it is sheathed: the
-- attacks stay the creature's montages and work even with the weapon put away.
-- Hand-held items (2026-11-17): with a weapon, a shield or a torch the game asks for animations that the creature does not have and
-- the body stays still. The pawn's weapons component (VWeaponsPairingComponent) knows which weapon and which shield are in hand
-- (WeaponForm/ShieldForm, TES forms with m_formID): they are written to hand.txt when they change, the C# mod sends them to the
