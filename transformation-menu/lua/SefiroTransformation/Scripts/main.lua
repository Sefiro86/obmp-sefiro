local PLAYER_TICK = "/Game/Dev/PlayerBlueprints/BP_OblivionPlayerCharacter.BP_OblivionPlayerCharacter_C:ReceiveTick"
local accum = 0
local localAddr = nil
local pcClass = nil

local remoteResetAt = 0
local remotePawns = {}         -- addresses of other players' pawns: discarded right away, without rechecking
local perfN, perfSum, perfMax, perfNext = 0, 0, 0, 0
local function perfAdd(ms)
    perfN, perfSum = perfN + 1, perfSum + ms
    if ms > perfMax then perfMax = ms end
    local now = os.clock()
    if now >= perfNext then
        if perfN > 0 and perfNext > 0 then
            log(string.format("perf: %d ticks in %d s, average %.3f ms, maximum %.1f ms", perfN, PERF_EVERY_S, perfSum / perfN, perfMax))
        end
        perfN, perfSum, perfMax, perfNext = 0, 0, 0, now + PERF_EVERY_S
    end
end

local function onPlayerTick(ctx, deltaParam)
    local pawn = ctx:get()
    if not valid(pawn) then return end
    local addr = addrOf(pawn)
    if remotePawns[addr] then
        -- an address may be reused by a new pawn (including ours, after a load): every 10 s
        -- everything is forgotten and rechecked
        local now = os.clock()
        if now < remoteResetAt then return end
        remotePawns, remoteResetAt = {}, now + 10
    end
    local isLocal = (addr == localAddr)
    if not isLocal then
        -- the Controller may be missing in the first frames: we recheck until it is there
        pcall(function()
            if not valid(pcClass) then pcClass = StaticFindObject("/Script/Engine.PlayerController") end
            local c = pawn.Controller
            isLocal = valid(c) and c:IsA(pcClass)
            if valid(c) and not isLocal then remotePawns[addr] = true end   -- it has a controller, but it is not ours
        end)
        if isLocal then localAddr = addr end
    end
    if not isLocal then return end
    cachedLocalPawn = pawn
    local t0 = os.clock()
    local dt = 0
    pcall(function() dt = deltaParam:get() end)
    accum = accum + dt
    local full = accum >= TICK_MS / 1000
    local okSc, errSc = pcall(scaleTick, pawn, full)   -- arm on every frame (only when scaled up): no stutter
    if not okSc and not scaleErrLogged then scaleErrLogged = true; log("setscale: " .. tostring(errSc)) end
    if full then
        accum = 0
        local ok, err = pcall(tick)
        if not ok then log("error: " .. tostring(err)) end
    end
    perfAdd((os.clock() - t0) * 1000)
end

local hooked = false
local function tryHook(where)
    if hooked then return end
    if pcall(RegisterHook, PLAYER_TICK, onPlayerTick) then
        hooked = true
        log("hooked to the player's ReceiveTick (" .. where .. ")")
    end
end
-- Never NotifyOnNewObject: UE4SS runs the callback on the thread that creates the object, including that of asynchronous
-- loading, concurrently with the game thread on the same Lua state. With "/Script/Engine.Character" (every pawn)
-- the game often crashed at startup (2026-11-16 04:34/04:39/04:46: exe+0xFE36C8 object creation notification ->
-- UE4SS+0x966F2 ... +0x181182, AV). Only hooks that UE4SS calls on the game thread.
tryHook("startup")
if not hooked then
    pcall(RegisterHook, "/Script/Engine.PlayerController:ClientRestart", function() tryHook("ClientRestart") end)
    pcall(RegisterInitGameStatePostHook, function() tryHook("InitGameState") end)
    pcall(RegisterBeginPlayPostHook, function(actor)
        if hooked then return end
        local ok, isPlayer = pcall(function() return actor:get():GetFullName():find("BP_OblivionPlayerCharacter_C", 1, true) ~= nil end)
        if ok and isPlayer then tryHook("player BeginPlay") end
    end)
end

-- ---------------------------------------------------------------- attacks
-- The player's attack code looks for combos in the human AnimBlueprint: with the creature's it finds nothing
-- ("Melee attack combo array is empty", main.dll) and the attack does not start. The creature's attack montages are played:
-- left click = left/right alternating, right button = power attack (the block is cancelled: it caused A-pose).
local attackSide = 1
playMontage = function(st, path)
    if not path then return end   -- creature without this montage
    local inst, montage = nil, ensure(path, "AnimMontage")
    if not montage then log("montage not in memory: " .. path); return end
    pcall(function() inst = st.body:GetAnimInstance() end)
    if not valid(inst) then return end
    local busy = false
    pcall(function() busy = inst:Montage_IsPlaying(montage) end)
    if busy then return end
    local ok, err = pcall(function() inst:Montage_Play(montage, 1.0, 0, 0.0, true) end)
    if not ok then log("Montage_Play: " .. tostring(err)) end
end
-- anim: "attack1" | "attack2" | "power" (same names as in the TransformAnim RPC)
local function playAnim(st, anim)
    if st and not st.revealTick and st.kind ~= "race" then pcall(playSound, st, "attack") end
    if not st or st.revealTick or st.kind == "race" then return end
    if anim == "power" then playMontage(st, st.def.power)
    elseif anim == "attack2" then playMontage(st, st.def.attacks[2])
    else playMontage(st, st.def.attacks[1]) end
end

-- Output to the other players: anim_out.txt ("<seq> <anim>", last 20 lines). The OblivionMP mod reads it
-- every 40 ms and sends the new lines with the TransformAnim RPC (ClientToClients, area).
local ANIM_OUT = (os.getenv("APPDATA") or "") .. "\\ReadyM.Launcher\\Oblivion\\Mods\\SefiroTransformation\\anim_out.txt"
local ANIM_IN = (os.getenv("APPDATA") or "") .. "\\ReadyM.Launcher\\Oblivion\\Mods\\SefiroTransformation\\anim_in.txt"
local outSeq, outLines = 0, {}
local function writeOut()
    local f = io.open(ANIM_OUT, "w")
    if not f then return end
    f:write(table.concat(outLines, "\n"))
    if #outLines > 0 then f:write("\n") end
    f:close()
end
local function emit(anim)
    outSeq = outSeq + 1
    table.insert(outLines, outSeq .. " " .. anim)
    while #outLines > 20 do table.remove(outLines, 1) end
    writeOut()
end
writeOut()   -- at startup the file is empty: the C# mod does not resend old events

attack = function(power)
    local st = active["self"]
    if not st or st.revealTick or st.kind == "race" then return end   -- race: the game attacks, with its own animations
    -- no burst: while the previous attack montage is playing, clicks are ignored (before, alternating
    -- left and right was enough to restart immediately). The damage is decided by the game anyway, at its own attack rate.
    local busy = false
    pcall(function() busy = st.body:GetAnimInstance():IsAnyMontagePlaying() end)
    if busy then return end
    local anim
    if power then
        anim = "power"
        st.lastAttackTick = tickCount
    else
        anim = (attackSide == 1) and "attack1" or "attack2"
        st.lastAttackTick = tickCount
        attackSide = attackSide % math.max(#st.def.attacks, 1) + 1
    end
    playAnim(st, anim)
    emit(anim)
end

-- Input from the other players: anim_in.txt ("<seq> 0x<pawn> <anim>"), written by the OblivionMP mod.
local inSeq = 0
readIncoming = function()
    local f = io.open(ANIM_IN, "r")
    if not f then return end
    local text = f:read("*a") or ""
    f:close()
    local maxSeq = 0
    local events = {}
    for line in text:gmatch("[^\r\n]+") do
        local seq, addr, anim = line:match("^(%d+)%s+(0x%x+)%s+(%S+)")
        seq = tonumber(seq)
        if seq then
            if seq > maxSeq then maxSeq = seq end
            table.insert(events, { seq = seq, key = string.format("0x%X", tonumber(addr) or 0), anim = anim })
        end
    end
    if maxSeq < inSeq then inSeq = 0 end          -- the C# mod restarted
    for _, e in ipairs(events) do
        if e.seq > inSeq then
            local st = active[e.key]
            if st then playAnim(st, e.anim) end
        end
    end
    if maxSeq > inSeq then inSeq = maxSeq end
end
