local function recordComp(st, c)
    local a = addrOf(c)
    if not a or st.hiddenComps[a] then return end
    local was = false
    pcall(function() was = c.bHiddenInGame == true end)
    st.hiddenComps[a] = { o = c, was = was }
end

local function recordActor(st, act)
    local a = addrOf(act)
    if not a or a == st.pawnAddr or st.hiddenActors[a] then return end
    local was = false
    pcall(function() was = act.bHidden == true end)
    st.hiddenActors[a] = { o = act, was = was }
end

-- Actors attached to the main mesh (weapons, shield, quiver, torch) and their descendants.
local function collectAttachedActors(st, comp, depth)
    if depth > 12 then return end
    local ok, children = pcall(function() return comp.AttachChildren end)
    if not ok or children == nil then return end
    children:ForEach(function(_, el)
        local c = el:get()
        if valid(c) then
            local owner = nil
            pcall(function() owner = c:GetOwner() end)
            if valid(owner) and addrOf(owner) ~= st.pawnAddr then recordActor(st, owner) end
            collectAttachedActors(st, c, depth + 1)
        end
    end)
end

-- Race form: weapons stay, but hair (beard, eyebrows) and quiver/arrows must be hidden. They are recognized by the
-- name of the component, of its mesh or of the owner actor. The first time the whole tree attached to the main mesh
-- is written to the log, to verify in game where the Remastered really keeps these pieces.
-- Pawn components: hair. Not "arrow": the nocked arrow (Drawn Arrow Mesh Component) is needed by the bow.
local RACE_HIDE_COMP = { "hair", "beard", "brow", "mustache", "moustache", "groom" }
-- Attached actors (not the pawn's) to hide: none. Quiver and arrows ended up on the ground only because the mesh
-- had no Quiver_Anchor; since the 2026-11-17 pak (blender_add_anchors.py) they attach to the back as in vanilla.
local RACE_HIDE_ACTOR = {}
-- Parts of the form itself (our assets): never hidden.
local RACE_KEEP = KEEP_VISIBLE   -- "obmp" plus the packs' words (keepVisible)
local function nameHas(text, words)
    text = text:lower()
    for _, w in ipairs(RACE_KEEP) do if text:find(w, 1, true) then return nil end end
    for _, w in ipairs(words) do if text:find(w, 1, true) then return w end end
    return nil
end
local function meshName(c)
    local n = ""
    pcall(function() n = fullName(c.SkeletalMesh) end)
    if n == "" or n == "?" then pcall(function() n = fullName(c.StaticMesh) end) end
    if n == "?" then n = "" end
    pcall(function() if n == "" then n = fullName(c.GroomAsset) end end)
    return n == "?" and "" or n
end
local function hideRaceExtras(st, comp, depth, dump)
    if depth > 12 then return end
    local ok, children = pcall(function() return comp.AttachChildren end)
    if not ok or children == nil then return end
    children:ForEach(function(_, el)
        local c = el:get()
        if not valid(c) then return end
        local owner = nil
        pcall(function() owner = c:GetOwner() end)
        local cn, mn = fullName(c), meshName(c)
        local ownerName = valid(owner) and fullName(owner) or "?"
        local foreign = valid(owner) and addrOf(owner) ~= st.pawnAddr
        local what = nil
        if foreign then
            what = nameHas(ownerName .. " " .. cn .. " " .. mn, RACE_HIDE_ACTOR)
            if what then recordActor(st, owner) end
        else
            what = nameHas(cn .. " " .. mn, RACE_HIDE_COMP)
            if what then recordComp(st, c) end
        end
        if dump then
            log(string.format("  %s%s | mesh %s | actor %s%s", string.rep("  ", depth), cn:match("[^%.]+$") or cn,
                mn ~= "" and (mn:match("[^%.]+$") or mn) or "-", foreign and (ownerName:match("[^%.]+$") or ownerName) or "pawn",
                what and ("  -> hidden (" .. what .. ")") or ""))
        end
        hideRaceExtras(st, c, depth + 1, dump)
    end)
end

-- Equipment signature: actors of the slots (clothes, head, rings) and number of pieces attached to the main mesh
-- and to the merged one (weapons, shield, quiver, torch). If it does not change, the full search for the pieces to
-- hide is skipped: every 0.5 s only the check that the ones already found stay hidden is repeated.
local function equipmentSignature(st)
    local sig = 0
    local pawn = st.pawn
    for i, n in ipairs(PARTS) do
        pcall(function() sig = sig + (addrOf(pawn[n].ChildActor) or 0) * i end)
    end
    pcall(function() sig = sig + st.m.AttachChildren:GetArrayNum() * 7919 end)
    pcall(function() sig = sig + pawn.MergedMeshComponent.MergedMeshComponent.AttachChildren:GetArrayNum() * 104729 end)
    return sig
end

local function hideHuman(st)
    local pawn = st.pawn
    local sig = equipmentSignature(st)
    -- in the first 5 s after the transformation we always search: the game puts pieces back late (the race's hair)
    if not st.scanUntil then st.scanUntil = tickCount + 50 end
    local rescan = sig ~= st.equipSig or tickCount < st.scanUntil
    st.equipSig = sig
    if rescan then
    for _, n in ipairs(PARTS) do
        pcall(function()
            local c = pawn[n]
            if not valid(c) then return end
            local child = nil
            pcall(function() child = c.ChildActor end)
            if valid(child) then recordActor(st, child) else recordComp(st, c) end
        end)
    end
    end
    if not rescan then
        -- nothing new: only the check below
    elseif st.kind ~= "race" then   -- race form: weapons stay, the body is the pawn's own mesh
        pcall(function()
            local inner = pawn.MergedMeshComponent.MergedMeshComponent
            if valid(inner) then recordComp(st, inner) end
        end)
        collectAttachedActors(st, st.m, 0)
    else
        local dump = DEBUG and not st.treeLogged   -- component tree only with diagnostics on (Shift+F3)
        if dump then log("tree attached to the main mesh (form " .. st.creature .. "):") end
        hideRaceExtras(st, st.m, 0, dump)
        pcall(function()   -- the quiver may be attached to the merged mesh instead of the main one
            local mm = pawn.MergedMeshComponent.MergedMeshComponent
            if valid(mm) and addrOf(mm) ~= addrOf(st.m) then
                if dump then log(" attached to the merged mesh:") end
                hideRaceExtras(st, mm, 0, dump)
            end
        end)
        -- also the pawn components not attached to the mesh (hair as a separate component)
        pcall(function()
            local all = pawn:K2_GetComponentsByClass(StaticFindObject("/Script/Engine.PrimitiveComponent"))
            all:ForEach(function(_, el)
                local c = el:get()
                if valid(c) then
                    local cn, mn = fullName(c), meshName(c)
                    local what = nameHas(cn .. " " .. mn, RACE_HIDE_COMP)
                    if what then recordComp(st, c) end
                    if dump then
                        log(string.format("  [pawn] %s | mesh %s%s", cn:match("[^%.]+$") or cn,
                            mn ~= "" and (mn:match("[^%.]+$") or mn) or "-", what and ("  -> hidden (" .. what .. ")") or ""))
                    end
                end
            end)
        end)
        if dump then
            pcall(function()
                local mm = pawn.MergedMeshComponent.MergedMeshComponent
                log("  merged mesh: " .. fullName(mm) .. " | mesh " .. meshName(mm))
            end)
        end
        st.treeLogged = true
    end
    for _, h in pairs(st.hiddenComps) do
        if valid(h.o) then pcall(function() if not h.o.bHiddenInGame then h.o:SetHiddenInGame(true, true) end end) end
    end
    for _, h in pairs(st.hiddenActors) do
        if valid(h.o) then pcall(function() if not h.o.bHidden then h.o:SetActorHiddenInGame(true) end end) end
    end
end

local function showHuman(st)
    for _, h in pairs(st.hiddenComps) do
        if valid(h.o) then pcall(function() h.o:SetHiddenInGame(h.was, true) end) end
    end
    for _, h in pairs(st.hiddenActors) do
        if valid(h.o) then pcall(function() h.o:SetActorHiddenInGame(h.was) end) end
    end
end

-- ---------------------------------------------------------------- apply the creature's body

-- Body animation update ONLY on the game thread (2026-11-17). The creature's "Reverse" AnimBlueprint
-- reads the player pawn's pairing components by calling Blueprint functions. In the parallel update
-- those calls go through ProcessEvent on a worker thread, and ReadyM's main.dll, which intercepts the calls on the
-- player's pawn, holds them back: sometimes the answer never arrives (frozen pose that slides), sometimes it stays
-- busy-waiting while the game thread waits for that task and the TES thread waits for the game thread (game hung,
-- 03:17, 03:30, 03:41: stacks in segnalazioni\stack_freeze_*.txt). With bUseMultiThreadedAnimationUpdate = false the
-- engine updates this instance on the game thread (UAnimInstance::NeedsImmediateUpdate). Cost: a single body per
-- transformed player, on the game thread instead of on a worker.
local function forceGameThreadAnim(st)
    -- main body instance: lightweight check, every 0.5 s
    local inst = nil
    pcall(function() inst = st.body:GetAnimInstance() end)
    if valid(inst) and addrOf(inst) ~= st.gtInst then
        pcall(function() inst.bUseMultiThreadedAnimationUpdate = false end)
        st.gtInst = addrOf(inst)
    end

end

-- a.ParallelAnimUpdate 0 while the LOCAL player is a creature (2026-11-17). Trial 03:55: with all 48
-- AnimInstances of our pawn already on the game thread the game still hung, with a parallel animation update
-- stuck in main.dll and no address of our pawn in its stack: probably an NPC's animation
-- (guards in combat) calling functions on the transformed player. With the variable at 0 the engine updates
-- all animations on the game thread, so no Blueprint call starts from a worker thread. It is set back to 1
-- as soon as the form is removed.
local ksl = nil
local parallelOff = false
local lastHand = nil            -- last line written to hand.txt (declared here: apply resets it)
local function setParallelAnim(on, why)
    if parallelOff == not on then return end
    local ok, err = pcall(function()
        if not valid(ksl) then ksl = StaticFindObject("/Script/Engine.Default__KismetSystemLibrary") end
        local pc = cachedLocalPawn.Controller
        -- in this engine 4 parameters: (context, command, PlayerController, false) - FATTIBILITA_NPC_CUSTOM.md
        ksl:ExecuteConsoleCommand(pc, "a.ParallelAnimUpdate " .. (on and "1" or "0"), pc, false)
    end)
    if ok then parallelOff = not on end
    log("a.ParallelAnimUpdate " .. (on and "1" or "0") .. " (" .. why .. "): " ..
        (ok and "ok" or ("ERROR, command not executed: " .. tostring(err):sub(1, 300))))
end

local function wearBody(st, bodyMesh, abp)
    local m = st.body
    setMesh(m, bodyMesh)
    -- the creature's own materials (otherwise the player's skin stays in slot 0)
    pcall(function()
        bodyMesh.Materials:ForEach(function(i, e)
            local mat = e:get().MaterialInterface
            if valid(mat) then m:SetMaterial(i - 1, mat) end
        end)
    end)
    pcall(function() m:SetAnimClass(abp) end)
    pcall(forceGameThreadAnim, st)
    -- right mouse button (block): the human layer put the troll in A-pose; it is detached
    local ok, err = pcall(function()
        local inst = m:GetAnimInstance()
        inst:UnlinkAnimClassLayers(inst.BlockAnimLayerClass)
    end)
    if not ok then log("block layer not detached: " .. tostring(err)) end
end

