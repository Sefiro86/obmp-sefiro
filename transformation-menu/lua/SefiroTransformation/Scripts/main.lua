-- Block (right mouse button). The ToggleBlockPressed handler immediately calls ToggleBlockReleased, but the game stays in
-- block for a few tenths of a second (trial 02:28:21: Block action, AnimAction 6, upper group 27). Creatures do not
-- have the block animation: the troll went into A-pose, the stag kept the frozen pose even afterwards, while
