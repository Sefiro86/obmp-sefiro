-- Trial 03:42: Altar's preload creates the objects right away and completes them asynchronously. StaticFindObject
-- found ABP_Reverse_Troll_C before it was done and SetAnimClass crashed (jump to 0x0 in
-- BlueprintLinkedAnimationLayersInitialized). An object is ready only with RF_LoadCompleted and without
-- RF_NeedLoad / RF_NeedPostLoad / RF_NeedPostLoadSubobjects; in addition we wait READY_TICKS after all of them are.
local RF_NEED_ANY = 0x400 + 0x1000 + 0x2000
local RF_LOAD_COMPLETED = 0x200000
local readyWait = {}             -- key -> { creature, at }: wait after the assets are ready
local READY_TICKS = 15          -- 1.5 s: the dependencies (the AnimBlueprint's TABP_* layers) finish too
local function loadedFully(o)
    local okNeed, needs = pcall(function() return o:HasAnyFlags(RF_NEED_ANY) end)
    local okDone, done = pcall(function() return o:HasAnyFlags(RF_LOAD_COMPLETED) end)
    if okNeed and needs then return false end
    if okDone and not done then return false end
    return true
end
local function ensure(path, cls)
    local o = StaticFindObject(canonical[path] or path)
    if valid(o) then return o end
    if tickCount < (nextScan[path] or 0) then return nil end
    nextScan[path] = tickCount + 10
    local want = path:lower()
    local all = FindAllOf(cls)
    if all then
        for _, obj in ipairs(all) do
            local p = fullName(obj):match("^%S+%s+(.+)$")
            if p and p:lower() == want then
                canonical[path] = p
                if p ~= path then log("canonical path: " .. p) end
                return obj
            end
        end
    end
    return nil
end

-- Altar preload per form (UVPairedAssetsLoadingSubsystem::RegisterPreloadRequestFromFormID): loads the creature's
-- assets asynchronously, without creating it. It replaces the server's "loading" creature, which
-- appeared alive next to the player (trial 03:35).
local PRELOAD_OWNER = 0x14            -- the player's form, as the request owner
local preloads = {}                   -- creature -> request id
local function preload(name)
    if preloads[name] then return end
    local def = CREATURES[name]
    local ok, res = pcall(function()
        local sub = FindFirstOf("VPairedAssetsLoadingSubsystem")
        if def.forms then
            local ids = {}
            for _, f in ipairs(def.forms) do ids[#ids + 1] = tostring(sub:RegisterPreloadRequestFromFormID(f, 2, PRELOAD_OWNER)) end
            return table.concat(ids, ",")
        end
        return sub:RegisterPreloadRequestFromFormID(def.form, 2, PRELOAD_OWNER)   -- 2 = High
    end)
    preloads[name] = ok and res or -1
    log(string.format("preload %s (form %08X): %s", name, def.form or (def.forms and def.forms[1]) or 0,
        ok and ("request " .. tostring(res)) or ("error " .. tostring(res))))
end
local function unpreload(name)
    local id = preloads[name]
    if not id then return end
    for _, st in pairs(active) do if st.creature == name then return end end
    preloads[name] = nil
    if id ~= -1 then
        for one in tostring(id):gmatch("[^,]+") do   -- races have one request per form ("a,b")
            local n = tonumber(one)
            if n and n ~= -1 then
                pcall(function() FindFirstOf("VPairedAssetsLoadingSubsystem"):UnregisterPreloadRequestFromRequestID(n, PRELOAD_OWNER) end)
            end
        end
    end
end

