local retryText, retryAt = nil, 0
local function readStateFile()
    local f = io.open(STATE_FILE, "r")
    if not f then
        if lastFileText ~= "" then lastFileText = ""; fileDesired = {} end
        return
    end
    local text = f:read("*a") or ""
    f:close()
    if text == lastFileText then return end
    if text == retryText and os.clock() < retryAt then return end   -- missing pack: new attempt every 5 s
    retryText = nil
    lastFileText = text
    localOverride = nil             -- a command from the server cancels the keyboard preview
    local desired = {}
    for line in text:gmatch("[^\r\n]+") do
        local key, name = line:match("^%s*(%S+)%s+(%S+)")
        if key and name and key ~= "v1" then
            name = name:lower()
            if key ~= "self" then key = string.format("0x%X", tonumber(key) or 0) end
            if knownOrRescan(name) then desired[key] = name
            else
                log("state.txt: unknown or unavailable form " .. name)
                -- pack perhaps not yet written by the C# mod: state.txt is reread in the next rounds (packs are
                -- reread at most once every 5 s by knownOrRescan)
                if name:find("^pack:") then lastFileText = nil; retryText = text; retryAt = os.clock() + 5 end
            end
        end
    end
    fileDesired = desired
    missingLogged = {}
    log("state.txt read: " .. text:gsub("[\r\n]+", " | "))
end

local function remoteActive()
    for k in pairs(active) do if k ~= "self" then return true end end
    return false
end

local function tick()
    tickCount = tickCount + 1
    if debugToggle then
        debugToggle = false
        DEBUG = not DEBUG
        log("diagnostics " .. (DEBUG and "on" or "off") .. " (Shift+F3)")
    end
    if tickCount % STATE_EVERY == 1 then readStateFile() end
    if toggleRequested then toggleRequested = false; togglePresets() end
    if modeRequested then
        modeRequested = false
        MODE_INDEX = MODE_INDEX % #MODES + 1
        log("=== MODE " .. MODES[MODE_INDEX] .. " === (Shift+F5)")
        for key, _ in pairs(active) do revert(key) end   -- the tick redoes it in the new mode
    end
    if readIncoming and remoteActive() then pcall(readIncoming) end
    if mouseAttack or mousePower then
        if not inputHookSeen and active["self"] then attack(mousePower) end
        mouseAttack, mousePower = false, false
    end

    for i = #showLater, 1, -1 do
        local s = showLater[i]
        if tickCount >= s.at then
            if valid(s.comp) then pcall(function() s.comp:SetHiddenInGame(s.hidden, false) end) end
            table.remove(showLater, i)
        end
    end

    local desired = {}
    for k, v in pairs(fileDesired) do desired[k] = v end
    if localOverride ~= nil then desired["self"] = (localOverride ~= "off") and localOverride or nil end

    -- remove what is no longer needed or whose pawn has changed/disappeared
    for key, st in pairs(active) do
        local stillPawn = valid(st.pawn) and valid(st.m)
        if key == "self" and stillPawn then
            local lp = localPawn()
            stillPawn = lp ~= nil and addrOf(lp) == st.pawnAddr
        end
        if not stillPawn then
            log("the pawn of " .. key .. " has changed (door, loading): form to redo")
            active[key] = nil          -- the old body is gone: nothing to restore
            if key == "self" and st.kind ~= "race" then setParallelAnim(true, "pawn changed") end
            if valid(st.holder) then pcall(function() st.holder:K2_DestroyComponent(st.holder) end) end
        elseif desired[key] ~= st.creature then
            local nextDef = CREATURES[desired[key]]
            if st.kind == "race" and nextDef and nextDef.pack and nextDef.pack == st.def.pack then
                -- only another skin of the same character: no race change. Removing it and putting it back right away
                -- (two OnRaceOrSexChanged in a row) crashed the game in ReadyM's main.dll (2026-11-17 06:53,
                -- AV memcpy from 0x0 when going from crimson to purple). Only the textures are changed.
                st.creature, st.def, st.gtInst = desired[key], nextDef, nil
                st.skinSets, st.skinMissingLogged = 0, false
                local okS, errS = pcall(applySkin, st)
                if not okS then log("skin: " .. tostring(errS)) end
                log("skin changed without changing race: " .. key .. " -> " .. st.creature)
            else
                revert(key)
            end
        end
    end
    for key, _ in pairs(pending) do
        if not desired[key] then pending[key] = nil end
    end

    -- apply what is missing
    for key, name in pairs(desired) do
        if not active[key] and (key == "self" or (nextTry[key] or 0) <= tickCount) then
            local pawn
            if key == "self" then pawn = localPawn() else pawn = pawnByAddress(tonumber(key)); nextTry[key] = tickCount + 20 end
            if pawn then
                local result, missing = apply(key, pawn, name)
                if result == "loading" then
                    local p = pending[key]
                    if not p or p.creature ~= name then
                        pending[key] = { creature = name, since = tickCount }
                        preload(name)
                        log("waiting for the game to load the assets of " .. name .. "...")
                    elseif tickCount - p.since > LOAD_GIVEUP_TICKS and not p.gaveUp then
                        p.gaveUp = true
                        log("assets not in memory after 15 s, missing: " .. tostring(missing)
                            .. " (preload: " .. tostring(preloads[name]) .. ")")
                    end
                elseif result == "ok" then
                    pending[key] = nil
                end
            elseif not missingLogged[key] then
                missingLogged[key] = true
                log("pawn not found for " .. key .. " (retrying)")
            end
        end
    end

    if markRequested then
        markRequested = false
        local st = active["self"]
        log("A-POSE MARK (Shift+F4): " .. (st and diagState(st) or "no active form"))
    end
    if DEBUG and active["self"] then pcall(diagTick, active["self"]) end

    for key, st in pairs(active) do
        if not st.revealTick and st.kind ~= "race" then
            pcall(hitReactTick, st)
            pcall(ragdollTick, st)
            if key == "self" then pcall(sheatheTick, st) end
            if key == "self" and tickCount % 5 == 0 then pcall(handTick, st) end
            if tickCount % 5 == 0 then pcall(soundTick, st) end
            local okB, errB = pcall(blockTick, st)
            if not okB and not st.blockErrLogged then st.blockErrLogged = true; log("block: " .. tostring(errB)) end
            local okF, errF = true, nil
            if tickCount % FREEZE_EVERY == 0 then okF, errF = pcall(freezeTick, st) end
            if not okF and not st.freezeErrLogged then st.freezeErrLogged = true; log("pose check: " .. tostring(errF)) end
            if key == "self" then pcall(sneakTick, st) end
        end
    end

    for _, st in pairs(active) do
        reveal(st)
        if tickCount % RESCAN_EVERY == 0 then maintain(st) end
    end
end

-- ---------------------------------------------------------------- setscale on the player (2026-11-17)
-- "setscale" (console bridge) changes the scale of the ACTOR: capsule, mesh and cameras scale together (trial 01:04:
-- first-person mesh and arm always in ratio 1). The capsule however grows around its center, so its
-- base drops below the floor by half the height x (new - old scale): at 2x that is ~90 cm, the movement starts
-- interpenetrated and the player gets stuck (01:04:44, setscale 2); at 1.5x it sometimes freed itself, sometimes not.
-- Fix: when the scale grows the actor is lifted by the same amount (teleport, no sweep), so the
-- feet stay on the floor. When it shrinks the capsule stays suspended and the player falls by themselves.
-- Third person: the camera arm length is in world units and does not scale with the actor: with the 2x body
-- the camera ended up inside the character. The length decided by the game is multiplied by the scale (if the game
-- changes it, for zoom or transitions, its value becomes the new base). First person: already follows the scale.
local scaleLast = nil
local scaleWatchUntil = 0
local arm3 = nil               -- { base, written } for the third-person TargetArmLength
local scaleErrLogged = false
local function vstr(v) return v and string.format("(%.1f %.1f %.1f)", v.X, v.Y, v.Z) or "?" end
local function moveReport(pawn, tag)
    local cm, cap = pawn.CharacterMovement, pawn.CapsuleComponent
    local loc, vel, mode, ground, hh = "?", "?", "?", "?", "?"
    pcall(function() loc = vstr(pawn:K2_GetActorLocation()) end)
    pcall(function() vel = vstr(cm.Velocity) end)
    pcall(function() mode = tostring(cm.MovementMode) end)
    pcall(function() ground = tostring(cm:IsMovingOnGround()) end)
    pcall(function() hh = string.format("%.1f", cap:GetScaledCapsuleHalfHeight()) end)
    log(string.format("scale %s: position %s, velocity %s, mode %s, on ground %s, half capsule %s", tag, loc, vel, mode, ground, hh))
end
local arm3Dirty = false        -- the arm length must be rewritten (scale just changed)
local function scaleTick(pawn, check)
    -- the scale change is checked every 0.1 s (check); the third-person arm is touched on every frame
    -- only while the body is not at scale 1, or once to put it back when it returns to it
    if check then
    local s = pawn:GetActorScale3D().Z
    if scaleLast == nil then scaleLast = s end
    if math.abs(s - scaleLast) > 0.001 then
        arm3Dirty = true
        if s > scaleLast then
            local hh = pawn.CapsuleComponent:GetUnscaledCapsuleHalfHeight()
            local loc = pawn:K2_GetActorLocation()
            local lift = hh * (s - scaleLast) + 2.0
            local to = { X = loc.X, Y = loc.Y, Z = loc.Z + lift }
            pawn:K2_SetActorLocation(to, false, {}, true)
            log(string.format("scale %.2f -> %.2f: lifted by %.1f cm (half capsule %.1f at scale 1)", scaleLast, s, lift, hh))
        else
            log(string.format("scale %.2f -> %.2f: the player falls by themselves", scaleLast, s))
        end
        scaleLast = s
        scaleWatchUntil = os.clock() + 3
        moveReport(pawn, "after the change")
    elseif scaleWatchUntil > 0 and os.clock() > scaleWatchUntil then
        scaleWatchUntil = 0
        moveReport(pawn, "3 s later")
    end
    end
    local s = scaleLast or 1
    if math.abs(s - 1) < 0.001 and not arm3Dirty then return end
    -- third person
    local arm = pawn.ThirdPersonCameraSpringArmComponent
    if valid(arm) then
        arm3Dirty = false
        local cur = arm.TargetArmLength
        if not arm3 then arm3 = { base = cur }
        elseif math.abs(cur - (arm3.written or -1)) > 0.01 then arm3.base = cur end   -- the game changed it
        local want = arm3.base * s
        if math.abs(cur - want) > 0.01 then arm.TargetArmLength = want end
        arm3.written = want
    end
end

