-- SefiroTransformation 0.9.0: the player swaps body and becomes a game creature (troll, ogre, minotaur...).
-- See E:\claude_magics\oblivion_mp\TRASFORMAZIONE_PLAYER.md (sections 9-10).
--
-- "Body swap" method on the player's pawn. The Nexus mod "Power of Dormin" showed that this can be done:
-- the technical information comes from there, the code is ours.
--  * MainSkeletalMeshComponent receives the creature's mesh and its AnimBlueprint (ABP_Reverse_<X>). The Reverse
--    template reads the pairing components that the player has too: the creature's walking, running, attacks, hits
--    and death follow the player's actions.
--  * StateMachineComponent.ActionStatePresetsDataTable = DT_ActionStatePresets_<X> (the creature's actions).
--  * The human parts (clothes, head, rings, merged body) and the attached actors (weapons, shield, quiver, torch)
--    are hidden, saving the state of each one; fur and horns are added as components in leader pose.
--  * Controls, camera, stats, inventory, spells and OblivionMP identity stay the player's own.
--
-- Rules learned (v0.2 crash, v0.1 freeze, Dormin):
--  * no UE object is kept in Lua unless the engine references it: the original mesh and materials live in a hidden
--    component ("holder") until the return, otherwise the GC frees them and putting them back crashes;
--  * no LoadAsset (it crashes even via ExecuteInGameThread): the assets are loaded by the game, through the
--    "loading" creature that the server places under the player;
--  * the work happens in the player's ReceiveTick (game thread), no LoopAsync;
--  * the body stays hidden for half a second after each change, until the animation starts (no T-pose).
--
-- Commands:
--  * state.txt in this folder, written by the OblivionMP mod ObmpExt.Transform (chat /transform):
--      "self <creature>"           the local player
--      "0x<address> <creature>"    another player's pawn (MappedActor.Pawn)
--  * local keys (preview on this PC only): Shift+F7 next creature, Shift+F8 back to normal,
--    Shift+F6 creature action presets yes/no (default yes: see SWAP_PRESETS).

